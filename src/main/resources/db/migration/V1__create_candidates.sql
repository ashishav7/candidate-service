create table candidates (
    id                  bigint generated by default as identity primary key,
    first_name          varchar(100) not null,
    last_name           varchar(100) not null,
    email               varchar(255) not null,
    phone               varchar(30),
    current_title       varchar(150),
    current_company     varchar(150),
    location            varchar(150),
    years_of_experience integer      not null,
    status              varchar(20)  not null,
    version             bigint       not null,
    created_at          timestamp with time zone not null,
    updated_at          timestamp with time zone not null,
    constraint uk_candidates_email unique (email),
    constraint ck_candidates_experience check (years_of_experience between 0 and 60)
);

create table candidate_skills (
    candidate_id bigint      not null,
    skill        varchar(50) not null,
    primary key (candidate_id, skill),
    constraint fk_candidate_skills_candidate
        foreign key (candidate_id) references candidates (id) on delete cascade
);

create index idx_candidates_status     on candidates (status);
create index idx_candidates_location   on candidates (location);
create index idx_candidates_experience on candidates (years_of_experience);
create index idx_candidates_created_at on candidates (created_at);
create index idx_candidate_skills_skill on candidate_skills (skill);
